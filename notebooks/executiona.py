# %matplotlib inline
from pathlib import Path
import json, csv, numpy as np
RUN_DIR=Path('/data/msctev1/runs/msctev1-20260829')
AGG=RUN_DIR/'aggregate'
print('Run:', RUN_DIR)

patients=['chb01','chb02','chb03','chb04','chb05','chb06','chb07','chb08','chb09','chb10','chb11','chb13','chb14','chb15','chb16','chb17','chb18','chb19','chb20','chb21','chb22','chb23','chb24']
missing=[p for p in patients if not (RUN_DIR/'folds'/p/'done.json').exists()]
assert not missing, missing
print('Verified fold markers:', len(patients))

rows=json.loads((AGG/'loso_results.json').read_text())
for r in rows: print(f"{r['patient']}: AUC={r['test_auc']:.4f} accuracy={r['test_accuracy']:.4f} epochs={r['epochs']}")

summary=json.loads((AGG/'summary.json').read_text())
print(f"Mean AUC: {summary['mean_auc']:.4f} ± {summary['std_auc']:.4f}")
print(f"Range: {summary['min_auc']:.4f} to {summary['max_auc']:.4f}")

events=json.loads((AGG/'event_level_results.json').read_text())
print('Event-level patients:', len(events))
print('Mean event sensitivity:', np.mean([r['event_sensitivity'] for r in events]))
print('Mean FPR/hour:', np.mean([r['fpr_hour'] for r in events]))

tta=json.loads((AGG/'tta_results.json').read_text())
print('BN adaptation patients:', len(tta))
print('Mean delta AUC:', np.mean([r['delta_auc'] for r in tta]))
print('Note:', tta[0]['adaptation_note'])

hard_tail=json.loads((AGG/'hard_tail_results.json').read_text())
print(f"Hard-tail Spearman rho={hard_tail['spearman_rho']:.4f}, p={hard_tail['p_value']:.4g}")

import matplotlib.pyplot as plt
plt.rcParams['font.family']='sans-serif'; plt.rcParams['font.sans-serif']=['Arial','Liberation Sans','DejaVu Sans']
aucs=[r['test_auc'] for r in rows]
plt.figure(figsize=(12,4)); plt.bar([r['patient'] for r in rows],aucs,color='#2166AC'); plt.axhline(np.mean(aucs),color='black',ls='--'); plt.xticks(rotation=60); plt.ylabel('LOSO AUC'); plt.title('MSCTEV1 Graph Spatio-Temporal LOSO Performance'); plt.tight_layout(); plt.show()

with np.load(RUN_DIR/'folds'/max(rows,key=lambda r:r['test_auc'])['patient']/'predictions.npz') as d: adj=d['adjacency']
plt.figure(figsize=(6,5)); plt.imshow(adj,cmap='viridis'); plt.colorbar(label='Learned edge weight'); plt.title('Learned Electrode Adjacency (best fold)'); plt.xlabel('Source electrode'); plt.ylabel('Target electrode'); plt.tight_layout(); plt.show()

points=hard_tail['patients']; x=[p['difficulty_score'] for p in points]; y=[p['test_auc'] for p in points]
plt.figure(figsize=(7,5)); plt.scatter(x,y,color='#D6604D');
for p in points: plt.annotate(p['patient'],(p['difficulty_score'],p['test_auc']),xytext=(4,3),textcoords='offset points',fontsize=8)
plt.xlabel('Interictal PSD KL difficulty score'); plt.ylabel('LOSO AUC'); plt.title('Hard-tail prediction'); plt.tight_layout(); plt.show()

